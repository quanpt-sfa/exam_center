COMMENT ON TABLE identity.instructor_profile IS 'Academic instructor profile.';
COMMENT ON TABLE identity.contact_point IS 'Multi-channel contact points per person.';
COMMENT ON TABLE identity.address IS 'Address records per person.';

COMMENT ON TABLE academic.department IS 'Academic department/unit.';
